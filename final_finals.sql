    (1, 'Верно (+)', '+'), 
    (2, 'Неверно (-)', '-')
) AS a(order_num, text, raw_value);

-- Начисление баллов по ключам (1 балл за совпадение с ключом)
INSERT INTO option_scores (option_id, scale_id, score)
SELECT ao.id, sc.id, 1
FROM answer_options ao
JOIN questions q ON ao.question_id = q.id
JOIN test_versions v ON q.version_id = v.id
JOIN tests t ON v.test_id = t.id
JOIN scales sc ON sc.version_id = v.id
WHERE t.code = 'self_attitude'
  AND (
    -- Интегральный показатель S
    (sc.code = 's_integral' AND (
        (ao.raw_value = '+' AND q.order_num IN (2, 5, 23, 27, 33, 42, 46, 48, 52, 53, 57)) OR 
        (ao.raw_value = '-' AND q.order_num IN (6, 9, 13, 14, 16, 18, 30, 35, 38, 39, 41, 43, 44, 45, 49, 50, 56))
    )) OR
    -- I. Шкала самоуверенности
    (sc.code = 'scale_1' AND (
        (ao.raw_value = '+' AND q.order_num IN (2, 23, 37, 42, 46)) OR 
        (ao.raw_value = '-' AND q.order_num IN (38, 39, 41))
